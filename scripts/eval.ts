// pnpm eval — asks the 15 test questions (eval/questions.json) through the chat API, scores each
// answer with deterministic checks (scripts/lib/eval-score.ts) and writes eval/report.md.
//   --url URL      API base URL (default http://localhost:8787); works against the live API too
//   --pace MS      wait between requests (default 10000: stays under 10/min and Groq's token limit)
//   --keep-cache   do not clear cached answers first (default: clear, so answers are fresh)
//   --only 1,9     run only these question ids; prints results, does not write the report
//   --skip-extra   skip the extra attack checks
// Needs the API running (pnpm dev) and apps/api/.dev.vars for the cache and match-score lookups.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { RELEVANCE_CUTOFF } from "../packages/shared/src/index.ts";
import { createDb } from "../apps/api/src/db/client.ts";
import { embedTexts } from "../apps/api/src/lib/embed.ts";
import { searchChunks } from "../apps/api/src/lib/search.ts";
import { askApi, type ApiResult } from "./lib/api-client.ts";
import { ROOT, redact, requireEnv, runMain } from "./lib/env.ts";
import {
  scoreExtra,
  scoreQuestion,
  type ChatOutcome,
  type EvalQuestion,
  type ExtraCheck,
  type Score,
} from "./lib/eval-score.ts";

interface Probe {
  question: string;
  expect: "answer" | "fallback";
}

interface TopMatch {
  score: number;
  slug: string;
}

interface QuestionRun {
  q: EvalQuestion;
  result: ApiResult;
  score: Score;
  top?: TopMatch;
}

interface ExtraRun {
  check: ExtraCheck;
  result: ApiResult;
  score: Score;
}

const TYPE_LABEL: Record<EvalQuestion["type"], string> = {
  direct: "Direct",
  "two-document": "Two documents",
  "not-covered": "Not covered",
  injection: "Injection",
};

const sleep = (ms: number) => new Promise<void>((resolve) => setTimeout(resolve, ms));

function flag(argv: string[], name: string): string | undefined {
  const i = argv.indexOf(name);
  return i >= 0 ? argv[i + 1] : undefined;
}

function readJson<T>(relative: string): T {
  return JSON.parse(readFileSync(join(ROOT, relative), "utf8")) as T;
}

function toOutcome(result: ApiResult): ChatOutcome {
  return {
    answer: result.answer,
    isFallback: result.meta?.isFallback ?? false,
    sources: (result.meta?.sources ?? []).map((s) => ({ index: s.index, slug: s.slug })),
    ...(result.error ? { error: result.error } : {}),
  };
}

/** Deletes cached answers so every question takes the full path. Returns how many were removed. */
async function clearAnswerCache(): Promise<number> {
  const url = requireEnv("UPSTASH_REDIS_REST_URL");
  const token = requireEnv("UPSTASH_REDIS_REST_TOKEN");
  const command = async (args: string[]): Promise<unknown> => {
    const res = await fetch(url, {
      method: "POST",
      headers: { authorization: `Bearer ${token}` },
      body: JSON.stringify(args),
    });
    if (!res.ok) throw new Error(`Upstash returned HTTP ${res.status}`);
    return ((await res.json()) as { result: unknown }).result;
  };
  const keys = (await command(["KEYS", "storeassist:answer:*"])) as string[];
  if (keys.length > 0) await command(["DEL", ...keys]);
  return keys.length;
}

/** Best match score for each text, straight from the database (no model call). */
async function topMatches(texts: string[]): Promise<TopMatch[]> {
  const db = createDb(requireEnv("DATABASE_URL"));
  const vectors = await embedTexts(texts, "RETRIEVAL_QUERY", {
    apiKey: requireEnv("GEMINI_API_KEY"),
  });
  const matches: TopMatch[] = [];
  for (const vector of vectors) {
    const [hit] = await searchChunks(db, vector, 1);
    matches.push({ score: hit?.score ?? 0, slug: hit?.slug ?? "-" });
  }
  return matches;
}

const cell = (text: string) => text.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
const seconds = (ms: number) => `${(ms / 1000).toFixed(1)} s`;

function writeReport(
  url: string,
  runs: QuestionRun[],
  extras: ExtraRun[],
  probes: { probe: Probe; top: TopMatch }[],
): string {
  const passed = runs.filter((r) => r.score.pass).length;
  const byType = (Object.keys(TYPE_LABEL) as EvalQuestion["type"][]).map((type) => {
    const ofType = runs.filter((r) => r.q.type === type);
    return `${TYPE_LABEL[type].toLowerCase()} ${ofType.filter((r) => r.score.pass).length}/${ofType.length}`;
  });
  const when = `${new Date().toISOString().slice(0, 16).replace("T", " ")} UTC`;
  const lines: string[] = [
    "# Eval report",
    "",
    `Generated by \`pnpm eval\` on ${when} against \`${url}\`. Relevance cutoff ${RELEVANCE_CUTOFF}.`,
    "Questions: `eval/questions.json`. Scoring rules: `scripts/lib/eval-score.ts` (string checks, no AI judge).",
    "",
    `## Score: ${passed}/${runs.length}`,
    "",
    byType.join(", "),
    "",
    "| # | Type | Question | Result | Top match | Model | Time | Cited pages |",
    "| --- | --- | --- | --- | --- | --- | --- | --- |",
  ];
  for (const run of runs) {
    const model = run.result.meta?.isFallback ? "none (fallback)" : (run.result.provider ?? "-");
    lines.push(
      `| ${run.q.id} | ${TYPE_LABEL[run.q.type]} | ${cell(run.q.question)} | ${
        run.score.pass ? "Pass" : "**Fail**"
      } | ${run.top ? `${run.top.score.toFixed(3)} ${run.top.slug}` : "-"} | ${model} | ${seconds(
        run.result.ms,
      )} | ${run.score.citedSlugs.join(", ") || "-"} |`,
    );
  }

  const failures = runs.filter((r) => !r.score.pass);
  if (failures.length > 0) {
    lines.push("", "### Failures", "");
    for (const run of failures) lines.push(`- **Q${run.q.id}:** ${run.score.reasons.join("; ")}`);
  }

  // Cutoff margin
  const answerable = runs.filter((r) => r.q.type === "direct" || r.q.type === "two-document");
  const notCovered = runs.filter((r) => r.q.type === "not-covered");
  const minAnswerable = Math.min(...answerable.map((r) => r.top?.score ?? 1));
  const maxNotCovered = Math.max(...notCovered.map((r) => r.top?.score ?? 0));
  lines.push(
    "",
    "## Relevance cutoff",
    "",
    `- Lowest top match among the 11 answerable questions: **${minAnswerable.toFixed(3)}**`,
    `- Highest top match among the 3 not-covered questions: **${maxNotCovered.toFixed(3)}**`,
    `- Cutoff ${RELEVANCE_CUTOFF}: margin ${(minAnswerable - RELEVANCE_CUTOFF).toFixed(3)} above, ${(
      RELEVANCE_CUTOFF - maxNotCovered
    ).toFixed(3)} below`,
  );
  if (probes.length > 0) {
    const sorted = probes.filter(
      ({ probe, top }) => (probe.expect === "answer") === top.score >= RELEVANCE_CUTOFF,
    ).length;
    lines.push(
      "",
      `Probe set (\`eval/probe.json\`, extra phrasings scored by search only): the cutoff sorts **${sorted}/${probes.length}** correctly.`,
      "",
      "| Question | Expected | Top match | Sorted correctly |",
      "| --- | --- | --- | --- |",
    );
    for (const { probe, top } of probes) {
      const ok = (probe.expect === "answer") === top.score >= RELEVANCE_CUTOFF;
      lines.push(
        `| ${cell(probe.question)} | ${probe.expect} | ${top.score.toFixed(3)} ${top.slug} | ${ok ? "yes" : "**no**"} |`,
      );
    }
  }

  if (extras.length > 0) {
    const extraPassed = extras.filter((e) => e.score.pass).length;
    lines.push(
      "",
      `## Extra attack checks: ${extraPassed}/${extras.length}`,
      "",
      "Not part of the 15/15 score (`eval/extra.json`).",
      "",
      "| Check | Result | Notes |",
      "| --- | --- | --- |",
    );
    for (const e of extras) {
      const kind = e.result.meta?.isFallback ? "fallback" : "model answer";
      lines.push(
        `| ${cell(e.check.label)} | ${e.score.pass ? "Pass" : "**Fail**"} | ${cell(
          e.score.pass ? kind : e.score.reasons.join("; "),
        )} |`,
      );
    }
  }

  lines.push("", "## Answers", "");
  for (const run of runs) {
    lines.push(`### Q${run.q.id}. ${run.q.question}`, "");
    lines.push(`Expected: ${run.q.expectedAnswer}`, "");
    const text =
      run.result.error && !run.result.answer ? `(error) ${run.result.error}` : run.result.answer;
    for (const line of text.split("\n")) lines.push(`> ${line}`);
    lines.push("");
  }
  for (const e of extras) {
    lines.push(`### Extra: ${e.check.label}`, "");
    const last = e.check.messages.at(-1)?.content ?? "";
    lines.push(`Asked: ${last}`, "");
    const text = e.result.error && !e.result.answer ? `(error) ${e.result.error}` : e.result.answer;
    for (const line of text.split("\n")) lines.push(`> ${line}`);
    lines.push("");
  }
  return redact(`${lines.join("\n").trimEnd()}\n`);
}

await runMain(async () => {
  const argv = process.argv.slice(2);
  const url = (flag(argv, "--url") ?? "http://localhost:8787").replace(/\/$/, "");
  const pace = Number(flag(argv, "--pace") ?? 10_000);
  const only = flag(argv, "--only")
    ?.split(",")
    .map((s) => Number(s.trim()))
    .filter(Number.isInteger);
  const skipExtra = argv.includes("--skip-extra") || Boolean(only);
  if (!Number.isFinite(pace) || pace < 0)
    throw new Error("--pace must be a number of milliseconds");

  const health = await fetch(`${url}/health`, { signal: AbortSignal.timeout(10_000) }).catch(
    () => undefined,
  );
  if (!health?.ok) throw new Error(`The API at ${url} is not answering. Start it with: pnpm dev`);

  const allQuestions = readJson<EvalQuestion[]>("eval/questions.json");
  const questions = only ? allQuestions.filter((q) => only.includes(q.id)) : allQuestions;
  const extras = skipExtra ? [] : readJson<ExtraCheck[]>("eval/extra.json");
  const probes = only ? [] : readJson<Probe[]>("eval/probe.json");

  if (!argv.includes("--keep-cache")) {
    console.log(`Cleared ${await clearAnswerCache()} cached answers.`);
  }

  console.log("Looking up top match scores...");
  const matches = await topMatches([
    ...questions.map((q) => q.question),
    ...probes.map((p) => p.question),
  ]);

  let first = true;
  const ask = async (messages: ExtraCheck["messages"]): Promise<ApiResult> => {
    if (!first && pace > 0) await sleep(pace);
    first = false;
    let result = await askApi(url, messages);
    if (result.status === 429) {
      const wait = (result.retryAfter ?? 30) + 1;
      console.log(`  rate limited, waiting ${wait} s and retrying once`);
      await sleep(wait * 1000);
      result = await askApi(url, messages);
    }
    return result;
  };

  const runs: QuestionRun[] = [];
  for (const [i, q] of questions.entries()) {
    const result = await ask([{ role: "user", content: q.question }]);
    const score = scoreQuestion(q, toOutcome(result));
    const top = matches[i];
    runs.push({ q, result, score, ...(top ? { top } : {}) });
    console.log(
      `Q${String(q.id).padStart(2)} ${score.pass ? "PASS" : "FAIL"}  ${seconds(result.ms).padStart(6)}  ${q.question}${
        score.pass ? "" : `\n      ${score.reasons.join("; ")}`
      }`,
    );
  }

  const extraRuns: ExtraRun[] = [];
  for (const check of extras) {
    const result = await ask(check.messages);
    const score = scoreExtra(check, toOutcome(result));
    extraRuns.push({ check, result, score });
    console.log(
      `extra ${score.pass ? "PASS" : "FAIL"}  ${check.label}${score.pass ? "" : `\n      ${score.reasons.join("; ")}`}`,
    );
  }

  const passed = runs.filter((r) => r.score.pass).length;
  console.log(`\nScore: ${passed}/${runs.length}`);
  if (only) {
    console.log("Partial run (--only): eval/report.md was not changed.");
  } else {
    const probeRows = probes.map((probe, i) => ({
      probe,
      top: matches[questions.length + i] ?? { score: 0, slug: "-" },
    }));
    writeFileSync(join(ROOT, "eval", "report.md"), writeReport(url, runs, extraRuns, probeRows));
    console.log("Wrote eval/report.md");
  }
  if (passed < runs.length) process.exitCode = 1;
});
